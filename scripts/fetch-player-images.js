const fs = require('fs');
const path = require('path');

const TEAMS_FILE = path.resolve(__dirname, '../src/data/teams.ts');
const OUTPUT_FILE = path.resolve(__dirname, '../src/data/player-images.ts');

const WIKI_API = 'https://en.wikipedia.org/api/rest_v1/page/summary';

let text = fs.readFileSync(TEAMS_FILE, 'utf8');

function extractPlayers(src) {
  const players = [];
  const teamRegex = /id:\s*"([^"]+)"[^}]*name:\s*"([^"]+)"/g;
  const playerRegex = /id:\s*"([^"]+)"[\s\S]*?name:\s*"([^"]+)"[\s\S]*?position:\s*"([^"]+)"/g;

  let match;
  while ((match = playerRegex.exec(src)) !== null) {
    players.push({ id: match[1], name: match[2], position: match[3] });
  }
  return players;
}

const players = extractPlayers(text);
console.log(`Found ${players.length} players`);

function sleep(ms) {
  return new Promise(r => setTimeout(r, ms));
}

async function fetchWithRetry(url, retries = 3) {
  for (let i = 0; i < retries; i++) {
    try {
      const res = await fetch(url, { headers: { 'User-Agent': 'WorldCup2026/1.0' } });
      if (res.status === 429) {
        const retryAfter = parseInt(res.headers.get('Retry-After') || '5', 10);
        console.log(`  Rate limited, waiting ${retryAfter}s...`);
        await sleep(retryAfter * 1000);
        continue;
      }
      if (res.status === 404) return null;
      if (!res.ok) {
        console.log(`  HTTP ${res.status}, retrying...`);
        await sleep(1000);
        continue;
      }
      return await res.json();
    } catch (e) {
      if (i === retries - 1) throw e;
      await sleep(1000);
    }
  }
  return null;
}

async function getPlayerImage(player) {
  const searchName = player.name
    .normalize('NFD').replace(/[\u0300-\u036f]/g, '')
    .replace(/['´`]/g, '')
    .replace(/[^a-zA-Z\s.-]/g, '')
    .trim();

  if (!searchName) return null;

  const searchTerms = searchName.includes(' ') ? searchName : `${searchName} footballer`;
  const url = `${WIKI_API}/${encodeURIComponent(searchTerms.replace(/\s+/g, '_'))}`;

  try {
    const data = await fetchWithRetry(url);
    if (data && data.thumbnail && data.thumbnail.source) {
      return data.thumbnail.source;
    }
    if (data && data.type === 'disambiguation') {
      return null;
    }
    if (data && data.extract && !data.thumbnail) {
      const pageUrl = `${WIKI_API}/${encodeURIComponent(searchTerms.split(' ').slice(0, 2).join('_').replace(/\s+/g, '_'))}`;
      const data2 = await fetchWithRetry(pageUrl);
      if (data2 && data2.thumbnail && data2.thumbnail.source) {
        return data2.thumbnail.source;
      }
    }
    return null;
  } catch (e) {
    return null;
  }
}

async function main() {
  const existing = {};
  if (fs.existsSync(OUTPUT_FILE)) {
    const existText = fs.readFileSync(OUTPUT_FILE, 'utf8');
    const mapMatch = existText.match(/const playerImages: Record<string, string> = ({[\s\S]*?});/);
    if (mapMatch) {
      try {
        const parsed = eval('(' + mapMatch[1] + ')');
        Object.assign(existing, parsed);
        console.log(`Loaded ${Object.keys(existing).length} existing images`);
      } catch (e) { }
    }
  }

  const todo = players.filter(p => !existing[p.id]);
  console.log(`${todo.length} players need images`);

  let found = 0;
  let notFound = 0;

  const batchSize = 5;
  for (let i = 0; i < todo.length; i += batchSize) {
    const batch = todo.slice(i, i + batchSize);
    const results = await Promise.all(batch.map(p => getPlayerImage(p)));

    for (let j = 0; j < batch.length; j++) {
      const player = batch[j];
      const img = results[j];
      if (img) {
        existing[player.id] = img;
        found++;
        if (found % 50 === 0) console.log(`  Progress: ${found} found, ${notFound} not found (${i + j + 1}/${todo.length})`);
      } else {
        notFound++;
      }
    }

    const count = i + batch.length;
    if (count % 100 === 0) {
      console.log(`  Checkpoint: ${count}/${todo.length}, found: ${found}, not found: ${notFound}`);
      writeOutput(existing);
    }

    await sleep(200);
  }

  console.log(`Done! Found: ${found}, Not found: ${notFound}, Total cached: ${Object.keys(existing).length}`);
  writeOutput(existing);
}

function writeOutput(images) {
  const lines = ['// Auto-generated by scripts/fetch-player-images.js', '// Maps player ID to Wikipedia thumbnail URL', '', 'export const playerImages: Record<string, string> = {'];
  const entries = Object.entries(images).sort((a, b) => a[0].localeCompare(b[0]));
  for (const [id, url] of entries) {
    lines.push(`  "${id}": "${url}",`);
  }
  lines.push('};', '', 'export function getPlayerImage(playerId: string): string | undefined {', '  return playerImages[playerId];', '}');
  fs.writeFileSync(OUTPUT_FILE, lines.join('\n'), 'utf8');
  console.log(`Written to ${OUTPUT_FILE}`);
}

main().catch(console.error);
