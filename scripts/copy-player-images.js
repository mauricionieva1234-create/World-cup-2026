let copied = 0;
let matched = 0;
const imageMap = {};

const teamDirs = fs.readdirSync(TFI_DIR, { withFileTypes: true }).filter(d => d.isDirectory());

for (const dir of teamDirs) {
  const dirPath = path.join(TFI_DIR, dir.name);
  const files = fs.readdirSync(dirPath).filter(f => f.endsWith('.avif'));
  for (const file of files) {
    const base = file.replace(/\.avif$/, '');
    const namePart = base.split('_')[0];

    let playerId = null;

    if (manualMap[namePart] !== undefined) {
      playerId = manualMap[namePart];
    }

    if (!playerId) {
      const parts = namePart.split('-');
      const first = parts.pop();
      const last = parts.join(' ');

      const variants = [
        normalize(`${first} ${last}`),
        normalize(`${last} ${first}`),
      ];
      if (parts.length > 1) variants.push(normalize(`${first} ${parts.join(' ')}`));

      for (const v of variants) {
        if (playerByName[v]) { playerId = playerByName[v].id; break; }
      }
    }

    if (playerId) {
      const destFile = `${playerId}.avif`;
      const destPath = path.join(PUBLIC_DIR, destFile);
      if (!fs.existsSync(destPath)) {
        fs.copyFileSync(path.join(dirPath, file), destPath);
        copied++;
      }
      imageMap[playerId] = `/players/${playerId}.avif`;
      matched++;
    } else {
      const tfid = (file.match(/_(\d+)\.avif$/) || [])[1];
    }
  }
}

